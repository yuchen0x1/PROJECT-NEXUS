// PHASE 6 (spec PART 8/9): the delivery stage that runs after a successful
// issue-fix pipeline when the hosting policy allows it.
//
// Chain: merge PR (policy.autoMerge + verification/review gates) → publish
// release (policy.autoPublish, patch version bump, generated notes) → reply
// + close the issue only when every PART 9.2 condition genuinely holds.

export function deliveryError(code, message) {
  return Object.assign(new Error(message), { code })
}

// Runtime evidence uses attempted/passed and verdict, not a synthetic status.
export function deliveryGate(verification, review) {
  if (verification?.attempted !== true || verification?.passed !== true) return 'verification did not run or pass'
  if (!verification.results?.some((item) => item.label === 'test' && item.attempted && item.ok)) return 'regression tests did not pass'
  if (review?.verdict !== 'approve') return 'independent review did not approve'
  if ((review.findings || []).some((item) => ['high', 'critical'].includes(String(item.severity).toLowerCase()))) return 'review reported a high-severity finding'
  return null
}

function bumpVersion(version, bump = 'patch') {
  const match = String(version || '').trim().match(/^v?(\d+)\.(\d+)\.(\d+)(?:-[0-9A-Za-z.-]+)?$/)
  if (!match) throw deliveryError('VERSION_UNPARSEABLE', `Cannot derive the next version from "${version}".`)
  const [major, minor, patch] = [Number(match[1]), Number(match[2]), Number(match[3])]
  const next = bump === 'major' ? `${major + 1}.0.0` : bump === 'minor' ? `${major}.${minor + 1}.0` : `${major}.${minor}.${patch + 1}`
  return { next, tag: `v${next}` }
}

export function nextVersionFromTag(latestTag, bump = 'patch') {
  const { next, tag } = bumpVersion(latestTag || 'v0.0.0', bump)
  return { version: next, tag, previous: latestTag || null }
}

// Reads the project version from the worktree to sanity-check releases.
export async function readProjectVersion(worktreePath) {
  const packageJsonPath = path.join(worktreePath, 'package.json')
  try {
    const content = await fs.readFile(packageJsonPath, 'utf8')
    const data = JSON.parse(content)
    return typeof data.version === 'string' ? data.version : null
  } catch { return null }
}

async function latestReleaseTag({ request, repository }) {
  const release = await request(`/repos/${repository}/releases/latest`).catch((error) => error.status === 404 ? null : Promise.reject(error))
  return release?.tag_name || null
}

export function buildReleaseNotes({ issue, tagName, delivery, verification, review, commitSha }) {
  return [
    `## What changed`,
    ``,
    `Release ${tagName} — automated fix for issue #${issue.number}: ${issue.title}`,
    ``,
    issue.analysis ? `**Root cause**: ${issue.analysis}` : '',
    ``,
    `**Verification**: ${verification?.attempted && verification?.passed ? 'PASS' : 'NOT VERIFIED'} — ${verification?.summary || 'no summary'}`,
    `**Independent review**: ${review?.verdict || 'unknown'}`,
    ``,
    `**Merged commit**: ${commitSha ? commitSha.slice(0, 12) : 'n/a'}${delivery.branch ? ` (branch \`${delivery.branch}\`)` : ''}`,
    ``,
    `Generated by PROJECT NEXUS under the repository hosting policy.`,
    issue.url ? `Resolves ${issue.url}` : `Resolves #${issue.number}`
  ].filter(Boolean).join('\n')
}

// Gate: merge only when the policy allows it AND the run genuinely passed
// verification AND the independent review found no high-severity problems.
export async function maybeMergePullRequest({ request, repository, pullRequest, policy, verification, review, signal } = {}) {
  if (!policy.autoMerge) return { merged: false, reason: 'policy: autoMerge disabled' }
  if (!pullRequest?.number) return { merged: false, reason: 'no pull request' }
  const blocked = deliveryGate(verification, review)
  if (blocked) return { merged: false, reason: blocked }
  if (!pullRequest.headSha) return { merged: false, reason: 'verified pull request head SHA is missing' }
  const ci = await waitForRemoteCI({ request, repository, pullRequest, policy, signal })
  if (!ci.passed) return { merged: false, reason: ci.reason, ci }
  const response = await request(`/repos/${repository}/pulls/${pullRequest.number}/merge`, {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ merge_method: 'squash', sha: pullRequest.headSha }),
    signal
  })
  return {
    merged: response.merged === true,
    ci,
    sha: response.sha || null,
    reason: response.merged === false ? (response.message || 'GitHub refused the merge') : 'merged by hosting policy'
  }
}

// Publish a release for the merged fix. Version = latest tag bumped by patch.
// Asset building: when the project defines a `build` script, run it in the
// worktree and upload `dist/`/`release/` artifacts up to the size budget.
export async function maybePublishRelease({ request, repository, token, policy, issue, delivery, verification, review, worktreePath, dataDir, signal, helpers: { onEvent = () => {}, onPlan = async () => {}, beforeUpload = async (_metadata, perform) => perform() } = {} } = {}) {
  if (!policy.autoPublish) return { published: false, reason: 'policy: autoPublish disabled' }
  if (!delivery.merged?.merged || !delivery.merged.sha) return { published: false, reason: 'nothing merged to release' }
  const blocked = deliveryGate(verification, review)
  if (blocked) return { published: false, reason: blocked }
  if (!delivery.security || !['CLEAN', 'FINDINGS'].includes(delivery.security.status)) return { published: false, reason: 'security scan missing or blocked' }
  // Release the exact tested commit. A squash merge can alter the resulting
  // tree; that commit must be checked out and verified before publishing.
  const checkout = await prepareMergedReleaseWorkspace({ dataDir, fullName: repository, token, commitSha: delivery.merged.sha, testedSha: delivery.commitSha, signal })
  worktreePath = checkout.path
  const head = await runCommand({ cwd: worktreePath, command: 'git rev-parse HEAD', signal })
  if (!head.ok || head.stdout.trim() !== delivery.merged.sha) return { published: false, reason: 'merged commit must be checked out and verified before release' }
  const previousTag = await latestReleaseTag({ request, repository })
  const { tag, version } = nextVersionFromTag(previousTag, 'patch')
  const plan = await createReleasePlan({ root: worktreePath, repository, commitSha: delivery.merged.sha, version, tag, policy })
  await onPlan(plan)
  if (plan.status !== 'Prepared') return { published: false, reason: plan.blockedReason, plan }
  const testResult = await runCommand({ cwd: worktreePath, command: plan.testCommand, signal, timeoutMs: 600_000 })
  if (!testResult.ok) throw deliveryError('RELEASE_TESTS_FAILED', 'Merged commit tests failed; publication stopped.')
  const security = await runSecurityScan({ root: worktreePath, signal })
  if (['CRITICAL', 'HIGH_RISK', 'BLOCKED'].includes(security.status)) throw deliveryError('RELEASE_SECURITY_BLOCKED', 'Merged commit security scan blocked publication.')

  const projectVersion = await readProjectVersion(worktreePath)
  if (projectVersion !== version) return { published: false, reason: `Tested project version must be ${version} before publishing ${tag}.` }
  const existing = await request(`/repos/${repository}/releases/tags/${encodeURIComponent(tag)}`).then(() => true).catch((error) => error.status === 404 ? false : Promise.reject(error))
  if (existing) return { published: false, reason: `release ${tag} already exists`, tag }

  const targetCommitish = delivery.merged?.sha || undefined
  const notes = buildReleaseNotes({ issue, tagName: tag, delivery: delivery, verification, review, commitSha: targetCommitish })
  onEvent({ type: 'release', detail: `Preparing draft release ${tag}.` })
  const release = await request(`/repos/${repository}/releases`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ tag_name: tag, name: tag, body: notes, draft: true, prerelease: false, target_commitish: targetCommitish }),
    signal
  })

  const assets = []
  const uploaded = await buildAndUploadReleaseAssets({ release, token, worktreePath, signal, onEvent, beforeUpload, requireSignature: plan.requiresSigning && !policy.allowUnsignedArtifacts })
  if (uploaded.length) assets.push(...uploaded)
  if (!assets.length && policy.allowSourceOnlyRelease !== true) throw deliveryError('RELEASE_ASSETS_MISSING', 'No release assets were uploaded; release remains a draft.')
  const published = await request(`/repos/${repository}/releases/${release.id}`, {
    method: 'PATCH', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ draft: false }), signal
  })
  if (published.draft !== false || !published.published_at) throw deliveryError('RELEASE_NOT_PUBLISHED', 'GitHub did not confirm release publication.')
  return { published: true, tag, version, releaseUrl: published.html_url || null, assets, previousTag: previousTag || null }
}

const ASSET_DIR_CANDIDATES = ['release', 'dist', 'build']
const ASSET_MAX_TOTAL_BYTES = 1024 * 1024 * 1024
const ASSET_MAX_FILES = 10
const ASSET_EXTENSIONS = /\.(exe|zip|tar\.gz|tgz|dmg|AppImage|deb|msi|apk|jar|whl|blockmap|yml|sha256|txt|json|md)$/i

async function sha256OfFile(filePath) {
  const hash = createHash('sha256')
  for await (const chunk of createReadStream(filePath)) hash.update(chunk)
  return hash.digest('hex')
}

async function buildAndUploadReleaseAssets({ release, token, worktreePath, signal, onEvent, beforeUpload, requireSignature }) {
  if (!token) throw deliveryError('GITHUB_NOT_CONFIGURED', 'Release upload credentials are unavailable.')
  const uploaded = []
  if (!release?.upload_url) return uploaded

  // Any build/upload failure leaves a draft and stops publication.
  let buildStatus = 'skipped'
  const packageJsonPath = path.join(worktreePath, 'package.json')
  try {
    const data = JSON.parse(await fs.readFile(packageJsonPath, 'utf8'))
    if (data.scripts?.build) {
      onEvent({ type: 'release_build', detail: 'Running the project build script for release assets.' })
      const result = await runCommand({ cwd: worktreePath, command: 'npm run build', timeoutMs: 600_000, outputLimitBytes: 512_000, signal })
      buildStatus = result.ok ? 'ok' : `failed (${result.exitCode})`
    }
  } catch (error) { if (error.code !== 'ENOENT') throw error; buildStatus = 'no build script' }
  if (buildStatus.startsWith('failed')) throw deliveryError('RELEASE_BUILD_FAILED', 'Release build failed; release remains a draft.')

  const artifacts = []
  for (const directory of ASSET_DIR_CANDIDATES) {
    const absolute = path.join(worktreePath, directory)
    const entries = await fs.readdir(absolute, { withFileTypes: true }).catch(() => [])
    for (const entry of entries) {
      if (!entry.isFile() || !ASSET_EXTENSIONS.test(entry.name)) continue
      const full = path.join(absolute, entry.name)
      const info = await fs.stat(full).catch(() => null)
      if (!info || info.size > ASSET_MAX_TOTAL_BYTES) continue
      artifacts.push({ path: full, name: entry.name, size: info.size })
    }
  }
  artifacts.sort((a, b) => b.size - a.size)

  let total = 0
  const uploadUrl = String(release.upload_url).replace(/\{.*$/, '')
  const parsedUploadUrl = new URL(uploadUrl)
  if (parsedUploadUrl.origin !== 'https://uploads.github.com') throw deliveryError('RELEASE_UPLOAD_ORIGIN', 'Release upload URL is not the trusted GitHub uploads origin.')
  for (const artifact of artifacts.slice(0, ASSET_MAX_FILES)) {
    if (total + artifact.size > ASSET_MAX_TOTAL_BYTES || signal?.aborted) break
    onEvent({ type: 'release_asset', detail: `Uploading ${artifact.name} (${Math.round(artifact.size / 1024)} KB).` })
    const checksum = await sha256OfFile(artifact.path)
    const signature = requireSignature ? await verifyArtifactSignature(artifact.path) : null
    if (requireSignature && !signature.valid) throw deliveryError('ARTIFACT_SIGNATURE_REQUIRED', `Artifact ${artifact.name} has no verified Authenticode signature; release remains a draft.`)
    const asset = await beforeUpload({ releaseId: release.id, name: artifact.name, sha256: checksum, size: artifact.size }, async () => {
    const response = await fetch(`${uploadUrl}?name=${encodeURIComponent(artifact.name)}`, {
      method: 'POST',
      headers: { Accept: 'application/vnd.github+json', Authorization: `Bearer ${token}`, 'Content-Type': 'application/octet-stream', 'Content-Length': String(artifact.size) },
      body: createReadStream(artifact.path), duplex: 'half', redirect: 'error',
      signal: signal ? AbortSignal.any([signal, AbortSignal.timeout(180_000)]) : AbortSignal.timeout(180_000)
    })
    if (!response.ok) throw deliveryError('RELEASE_UPLOAD_FAILED', `Asset upload failed (${response.status}); release remains a draft.`)
    return await response.json()
    })
    if (asset.digest && asset.digest !== `sha256:${checksum}`) throw deliveryError('RELEASE_CHECKSUM_MISMATCH', 'Uploaded asset checksum does not match the local artifact.')
    total += artifact.size
    uploaded.push({ name: artifact.name, size: artifact.size, sha256: checksum, url: asset.browser_download_url || null })
  }
  return uploaded
}

// PART 9.2: close the issue only when fix + tests + push/merge + release (or
// an explicit merge-only policy) + posted reply all genuinely happened.
export function shouldCloseIssue({ policy, delivery, verification, review }) {
  if (policy.closeIssueAfterRelease === false && policy.closeIssueAfterMerge !== true) return { close: false, reason: 'policy: closeIssueAfterRelease disabled' }
  const blocked = deliveryGate(verification, review)
  if (blocked) return { close: false, reason: blocked }
  if (!delivery.pushed) return { close: false, reason: 'changes were never pushed' }
  if (!delivery.issueCommented) return { close: false, reason: 'the report reply was never posted' }
  if (!delivery.merged?.merged) return { close: false, reason: 'fix has not been merged' }
  if (!delivery.released?.published && policy.closeIssueAfterMerge !== true) return { close: false, reason: 'no published release or explicit merge-only closure policy' }
  // Without autoPublish, closing after a genuine merge is the documented
  // project-policy path allowed by PART 9.2 condition 4.
  return { close: true, reason: 'all delivery gates passed' }
}

export async function maybeCloseIssue({ request, repository, issueNumber, policy, delivery, verification, review, signal, helpers: { onEvent = () => {} } = {} } = {}) {
  const decision = shouldCloseIssue({ policy, delivery, verification, review })
  if (!decision.close) return { closed: false, reason: decision.reason }
  onEvent({ type: 'issue_close', detail: `Closing issue #${issueNumber}: ${decision.reason}.` })
  const closed = await request(`/repos/${repository}/issues/${Number(issueNumber)}`, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ state: 'closed', state_reason: 'completed' }),
    signal
  })
  return { closed: closed.state === 'closed', reason: decision.reason }
}
