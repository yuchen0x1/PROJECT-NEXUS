import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import http from 'node:http'
import net from 'node:net'
import os from 'node:os'
import path from 'node:path'
import process from 'node:process'
import { spawn, spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { chromium } from 'playwright'
import { registerLocalProject } from '../server/services/local-projects.mjs'

const require = createRequire(import.meta.url)
const electronExecutable = require('electron')
const appRoot = path.resolve(import.meta.dirname, '..')
const screenshotPath = path.join(appRoot, 'docs', 'screenshots', 'phase4', 'local-agent-workflow.png')
const tempRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'nexus-phase4-desktop-ui-'))
const dataRoot = path.join(tempRoot, 'nexus user data')
const projectPath = path.join(tempRoot, '测试 项目')
const profilePath = path.join(tempRoot, 'electron profile')
const originalSource = 'export const greeting = "hello"\n'
const addedSource = 'export const phase4Fixture = true\n'
const prompt = 'Fixture UI check: update the greeting and add the fixture marker module.'
const outputLimit = 128 * 1024
const startupTimeoutMs = 45_000
const devToolsPattern = /DevTools listening on (ws:\/\/127\.0\.0\.1:\d+\/devtools\/browser\/[^\s]+)/

let child
let browser
let providerServer
let providerRequests = 0
let output = ''
let devToolsEndpoint = null
let childExit = null
let failed = false
let capturedProviderPayload = null

function appendOutput(chunk) {
  output = (output + chunk.toString()).slice(-outputLimit)
  devToolsEndpoint ||= output.match(devToolsPattern)?.[1] || null
}

function waitFor(predicate, timeoutMs, label) {
  const startedAt = Date.now()
  return new Promise((resolve, reject) => {
    const poll = () => {
      if (predicate()) return resolve()
      if (childExit) return reject(new Error(`Electron exited before ${label} (code ${childExit.code ?? 'unknown'}, signal ${childExit.signal ?? 'none'}).`))
      if (Date.now() - startedAt >= timeoutMs) return reject(new Error(`Timed out waiting for ${label} after ${timeoutMs} ms.`))
      setTimeout(poll, 100)
    }
    poll()
  })
}

async function freePort() {
  const server = net.createServer()
  await new Promise((resolve, reject) => server.once('error', reject).listen(0, '127.0.0.1', resolve))
  const port = server.address().port
  await new Promise((resolve) => server.close(resolve))
  return port
}

function stopProcessTree() {
  if (!child?.pid || childExit) return
  if (process.platform === 'win32') {
    spawnSync('taskkill.exe', ['/PID', String(child.pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore' })
  } else {
    child.kill('SIGTERM')
  }
}

try {
  await fs.mkdir(path.join(projectPath, 'src'), { recursive: true })
  await fs.mkdir(profilePath, { recursive: true })
  await fs.mkdir(dataRoot, { recursive: true })
  // Pin the UI language so the Playwright selectors below stay deterministic.
  await fs.writeFile(path.join(dataRoot, 'desktop-settings.json'), JSON.stringify({ language: 'en-US' }, null, 2), 'utf8')
  await fs.writeFile(path.join(projectPath, '.gitignore'), 'ignored.txt\n', 'utf8')
  await fs.writeFile(path.join(projectPath, 'ignored.txt'), 'fixture-only ignored source\n', 'utf8')
  await fs.writeFile(path.join(projectPath, '.env'), 'API_KEY=fixture-secret-must-not-leave-this-machine\n', 'utf8')
  await fs.writeFile(path.join(projectPath, 'README.md'), '# Temporary fixture project\n', 'utf8')
  await fs.writeFile(path.join(projectPath, 'src', 'index.js'), originalSource, 'utf8')
  const sourceHashBefore = crypto.createHash('sha256').update(await fs.readFile(path.join(projectPath, 'src', 'index.js'))).digest('hex')
  const { project } = await registerLocalProject({ dataDir: dataRoot, folderPath: projectPath })

  providerServer = http.createServer((request, response) => {
    let raw = ''
    request.setEncoding('utf8')
    request.on('data', (chunk) => { raw += chunk })
    request.on('end', () => {
      providerRequests += 1
      assert.equal(request.url, '/v1/chat/completions')
      assert.equal(request.headers.authorization, 'Bearer phase4-ui-fixture-key')
      const payload = JSON.parse(raw)
      capturedProviderPayload = payload
      const generated = {
        rationale: 'Fixture response generated by the local desktop UI smoke test.',
        operations: [
          { action: 'replace', path: 'src/index.js', content: 'export const greeting = "hello, fixture"\n' },
          { action: 'create', path: 'src/phase4-fixture.js', content: addedSource }
        ]
      }
      assert.ok(payload.messages.some((message) => String(message.content).includes(prompt)))
      response.writeHead(200, { 'content-type': 'application/json' })
      response.end(JSON.stringify({
        choices: [{ message: { content: JSON.stringify(generated) } }],
        usage: { prompt_tokens: 61, completion_tokens: 24, total_tokens: 85 }
      }))
    })
  })
  await new Promise((resolve, reject) => providerServer.once('error', reject).listen(0, '127.0.0.1', resolve))
  const providerUrl = `http://127.0.0.1:${providerServer.address().port}`

  const debuggingPort = await freePort()
  child = spawn(electronExecutable, [
    `--remote-debugging-address=127.0.0.1`,
    `--remote-debugging-port=${debuggingPort}`,
    `--user-data-dir=${profilePath}`,
    appRoot,
    '--nexus-smoke-test'
  ], {
    cwd: appRoot,
    env: {
      ...process.env,
      NEXUS_DESKTOP_DATA_DIR: dataRoot,
      AI_PROVIDER_KIND: 'openai-compatible',
      AI_BASE_URL: providerUrl,
      AI_API_KEY: 'phase4-ui-fixture-key',
      AI_MODEL: 'fixture-ui-model',
      AI_REQUEST_TIMEOUT_MS: '5000',
      AI_MAX_RETRIES: '0',
      ELECTRON_ENABLE_LOGGING: '1',
      ELECTRON_DISABLE_SECURITY_WARNINGS: 'true'
    },
    windowsHide: true,
    stdio: ['ignore', 'pipe', 'pipe']
  })

  child.stdout.setEncoding('utf8')
  child.stderr.setEncoding('utf8')
  child.stdout.on('data', appendOutput)
  child.stderr.on('data', appendOutput)
  child.on('error', (error) => { childExit = { code: null, signal: null, error } })
  child.on('exit', (code, signal) => { childExit = { code, signal } })

  await waitFor(() => output.includes('NEXUS_DESKTOP_TRACE:app-ready'), 20_000, 'Electron app readiness')
  await waitFor(() => output.includes('NEXUS_DESKTOP_TRACE:local-service-ready'), startupTimeoutMs, 'local service readiness')
  const devToolsUrl = `http://127.0.0.1:${debuggingPort}/json/version`
  for (let attempt = 0; attempt < 100; attempt += 1) {
    try {
      const version = await fetch(devToolsUrl).then((response) => response.json())
      if (version.webSocketDebuggerUrl) { devToolsEndpoint = version.webSocketDebuggerUrl; break }
    } catch {}
    await new Promise((resolve) => setTimeout(resolve, 100))
  }
  await waitFor(() => devToolsEndpoint, 10_000, 'Electron DevTools endpoint')
  browser = await chromium.connectOverCDP(devToolsEndpoint, { timeout: 15_000 })
  const context = browser.contexts()[0]
  assert.ok(context, 'The launched Electron app should expose a Chromium context.')
  const page = context.pages()[0] || await context.waitForEvent('page', { timeout: 15_000 })
  await page.waitForLoadState('domcontentloaded', { timeout: 20_000 })
  await page.getByRole('heading', { name: 'Workbench', exact: true }).waitFor({ timeout: 20_000 })
  await page.getByRole('button', { name: 'AI Agent', exact: true }).click()
  await page.getByRole('heading', { name: 'Describe a code change', exact: true }).waitFor({ timeout: 10_000 })
  await page.getByText('Provider ready', { exact: true }).waitFor({ timeout: 10_000 })
  await page.getByRole('heading', { name: 'Isolated change review', exact: true }).waitFor()

  await page.getByLabel(/Request/).fill(prompt)
  await page.getByLabel(/I reviewed this disclosure and authorize sending/).check()
  const generateButton = page.getByRole('button', { name: 'Generate isolated changes', exact: true })
  assert.equal(await generateButton.isEnabled(), true)
  await generateButton.click()
  await page.locator('.nx-agent-status.succeeded').first().waitFor({ timeout: 20_000 })
  await page.getByText('Fixture response generated by the local desktop UI smoke test.', { exact: true }).waitFor({ timeout: 10_000 })
  await page.getByText('85 tokens', { exact: true }).waitFor({ timeout: 10_000 })
  await page.getByText('src/phase4-fixture.js', { exact: true }).waitFor({ timeout: 10_000 })
  await page.locator('.nx-agent-diff summary').first().click()
  await page.getByText('hello, fixture', { exact: false }).waitFor({ timeout: 10_000 })

  assert.equal(providerRequests, 1, 'Only the local test provider should handle the generated task.')
  assert.ok(capturedProviderPayload, 'The local fixture provider should receive the task context.')
  assert.equal(JSON.stringify(capturedProviderPayload).includes('fixture-secret-must-not-leave-this-machine'), false, 'Secret-shaped files must not leave the workstation.')
  assert.equal(JSON.stringify(capturedProviderPayload).includes('fixture-only ignored source'), false, 'Project-ignored files must not leave the workstation.')
  assert.equal(await fs.readFile(path.join(projectPath, 'src', 'index.js'), 'utf8'), originalSource, 'The registered source project must remain untouched.')
  await assert.rejects(fs.access(path.join(projectPath, 'src', 'phase4-fixture.js')), { code: 'ENOENT' })
  assert.equal(crypto.createHash('sha256').update(await fs.readFile(path.join(projectPath, 'src', 'index.js'))).digest('hex'), sourceHashBefore)

  await fs.mkdir(path.dirname(screenshotPath), { recursive: true })
  await page.screenshot({ path: screenshotPath, fullPage: true })
  console.log('PASS: Electron rendered the native AI Agent page and connected it to the authenticated local API.')
  console.log('PASS: The page submitted a fixture task through the local test provider and rendered its multi-file diff and usage.')
  console.log('PASS: The Chinese/space-path source fixture remained unchanged; generated files stayed in the isolated app-data workspace.')
  console.log(`PASS: Runtime screenshot saved to ${screenshotPath}`)
  console.log(`Provider requests: ${providerRequests}; fixture project id: ${project.id}`)
} catch (error) {
  failed = true
  const diagnostics = path.join(tempRoot, 'diagnostics')
  await fs.mkdir(diagnostics, { recursive: true }).catch(() => {})
  await fs.writeFile(path.join(diagnostics, 'electron-output.log'), output, 'utf8').catch(() => {})
  console.error(`Desktop UI smoke failed. Temporary data and logs retained at: ${tempRoot}`)
  if (childExit?.error) console.error(childExit.error)
  throw error
} finally {
  await browser?.close().catch(() => {})
  stopProcessTree()
  if (child && !childExit) {
    await Promise.race([
      new Promise((resolve) => child.once('exit', resolve)),
      new Promise((resolve) => setTimeout(resolve, 3_000))
    ])
  }
  if (!childExit) stopProcessTree()
  await new Promise((resolve) => providerServer?.close(resolve) || resolve())
  if (!failed) await fs.rm(tempRoot, { recursive: true, force: true })
}

